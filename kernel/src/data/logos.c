void print_from_array(char *array[], size_t n) { printf_("%s", array[n]); }

void print_rarity(enum rarity r) {
  switch (r) {
  case COMMON:
    set_text_colour(0xffffff);
    print_from_array(common_logos, random_range(0, NUM_COMMON_LOGOS - 1));
    break;
  case UNCOMMON:
    set_text_colour(0xabcaff);
    print_from_array(uncommon_logos, random_range(0, NUM_UNCOMMON_LOGOS - 1));
    break;
  case RARE:
    set_text_colour(0xee3330);
    print_from_array(rare_logos, random_range(0, NUM_RARE_LOGOS - 1));
    break;
  case EPIC:
    set_text_colour(0xa63fff);
    print_from_array(epic_logos, random_range(0, NUM_EPIC_LOGOS - 1));
    break;
  case LEGENDARY:
    set_text_colour(0xffc611);
    print_from_array(legendary_logos, random_range(0, NUM_LEGENDARY_LOGOS - 1));
    break;
  case MYTHICAL:
    set_text_colour(0xE1C1FF);
    print_from_array(mythical_logos, random_range(0, NUM_MYTHICAL_LOGOS - 1));
    break;
  }
  crlf();
}

// I would never waste dev time...
void print_random_logo() {
  uint32_t rand = random_uint32();

  if (rand < (uint64_t)MYTHICAL_LOGO_CHANCE * UINT32_MAX / 100) {
    print_rarity(MYTHICAL);
  } else if (rand < (uint64_t)LEGENDARY_LOGO_CHANCE * UINT32_MAX / 100) {
    print_rarity(LEGENDARY);
  } else if (rand < (uint64_t)EPIC_LOGO_CHANCE * UINT32_MAX / 100) {
    print_rarity(EPIC);
  } else if (rand < (uint64_t)RARE_LOGO_CHANCE * UINT32_MAX / 100) {
    print_rarity(RARE);
  } else if (rand < (uint64_t)UNCOMMON_LOGO_CHANCE * UINT32_MAX / 100) {
    print_rarity(UNCOMMON);
  } else {
    print_rarity(COMMON);
  }
}